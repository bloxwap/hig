import {readFileSync,writeFileSync,mkdirSync,copyFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {assertGeneratedFonts} from './generated-fonts.mjs';

const source='packages/native-fonts/fonts';
const target='packages/og-fonts';
const canonical=JSON.parse(readFileSync(`${source}/manifest.json`,'utf8'));
const selected=new Set(['BloxwapSans.ttf','BloxwapSans-SemiBold.ttf','BloxwapSans-Bold.ttf','BloxwapMono.ttf']);
const faces=canonical.faces.filter(face=>selected.has(face.asset));
if(faces.length!==selected.size)throw new Error('The canonical font manifest is missing an OG face');
const manifest={...canonical,sources:Object.fromEntries(Object.entries(canonical.sources).filter(([path])=>/\/Bloxwap(?:Sans|Mono)\//.test(path))),faces,outputs:Object.fromEntries(faces.map(face=>[face.asset,canonical.outputs[face.asset]]))};
mkdirSync(`${target}/fonts`,{recursive:true});mkdirSync(`${target}/src`,{recursive:true});
if(!process.argv.includes('--metadata-only')){
 assertGeneratedFonts(undefined,['native-fonts']);
 for(const face of faces){
  const file=`${source}/${face.asset}`;
  if(createHash('sha256').update(readFileSync(file)).digest('hex')!==manifest.outputs[face.asset])throw new Error(`Canonical font hash mismatch: ${face.asset}`);
  copyFileSync(file,`${target}/fonts/${face.asset}`);
 }
}
writeFileSync(`${target}/fonts/manifest.json`,JSON.stringify(manifest,null,2)+'\n');
writeFileSync(`${target}/src/index.ts`,`// Generated by scripts/generate-og-fonts.mjs from the canonical native-font manifest.\nexport const fontManifest = ${JSON.stringify(manifest,null,2)} as const;\n`);
console.log(`OG fonts: ${faces.length} Latin faces; canonical SHA-256 hashes preserved`);
