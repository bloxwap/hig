import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {oklchToSrgb,oklchToDisplayP3,srgbHexToDisplayP3,p3ChannelsToHex} from './color-space.mjs';
const upstream=JSON.parse(readFileSync('packages/tokens/upstream-palette.json','utf8'));
const sourceColors={web:upstream.semanticOklch,android:Object.fromEntries(Object.entries(upstream.semanticOklch).map(([k,v])=>[k,oklchToSrgb(v)])),iosDisplayP3:Object.fromEntries(Object.entries(upstream.semanticOklch).map(([k,v])=>[k,oklchToDisplayP3(v)]))};
const tokens=JSON.parse(readFileSync('packages/tokens/source.json','utf8'));
mkdirSync('packages/tokens/generated',{recursive:true});mkdirSync('evidence',{recursive:true});mkdirSync('packages/tokens/src',{recursive:true});
for(const color of Object.values(tokens.colors)){if(color.oklch)color.srgb=oklchToSrgb(color.oklch);}
const srgb=Object.fromEntries(Object.entries(tokens.colors).map(([k,v])=>[k,v.srgb]));
const iosP3=Object.fromEntries(Object.entries(tokens.colors).filter(([,v])=>v.p3).map(([k,v])=>[k,{space:'display-p3',components:v.p3,alpha:1}]));
writeFileSync('packages/tokens/src/index.ts',`// Generated by npm run generate.
export const tokens = ${JSON.stringify(tokens,null,2)} as const;
// Small native bindings keep a basic control from retaining color-space/provenance metadata.
export const nativeSrgb = ${JSON.stringify(srgb,null,2)} as const;
export const nativeMetrics = ${JSON.stringify({space:tokens.space,radius:tokens.radius,density:tokens.density,motion:tokens.motion},null,2)} as const;
export const sourceColors = ${JSON.stringify(sourceColors,null,2)} as const;
export const nativeColors = ${JSON.stringify({android:srgb,ios:srgb,iosDisplayP3:Object.fromEntries(Object.entries(tokens.colors).map(([k,v])=>[k,v.p3?p3ChannelsToHex(v.p3):v.oklch?oklchToDisplayP3(v.oklch):srgbHexToDisplayP3(v.srgb)])),iosP3},null,2)} as const;
export function withAlpha(hex: string, alpha: number): string { if (!/^#[a-fA-F0-9]{6}$/.test(hex) || !Number.isFinite(alpha) || alpha<0 || alpha>1) throw new Error('Invalid sRGB/alpha'); return hex + Math.round(alpha*255).toString(16).padStart(2,'0'); }
`);
const vars=Object.entries(srgb).map(([k,v])=>`  --hig-${k}: ${v};`).join('\n');
const p3=Object.entries(tokens.colors).filter(([,v])=>v.p3).map(([k,v])=>`  --hig-${k}: color(display-p3 ${v.p3.join(' ')});`).join('\n');
const oklch=Object.entries(tokens.colors).filter(([,v])=>v.oklch).map(([k,v])=>`  --hig-${k}: ${v.oklch};`).join('\n');
const sourceVars=Object.entries(upstream.semanticOklch).map(([k,v])=>`  --hig-source-${k}: ${v};`).join('\n');
const space=Object.entries(tokens.space).map(([k,v])=>`  --hig-space-${k}: ${v/16}rem;`).join('\n');
writeFileSync('packages/tokens/generated/tokens.css',`:root { color-scheme: dark;
${vars}
${space}
}
@supports (color: oklch(0.5 0 0)) { :root {
${oklch}
${sourceVars}
} }
@supports (color: color(display-p3 1 1 1)) { :root {
${p3}
} }
`);
writeFileSync('packages/tokens/generated/manifest.json',JSON.stringify(tokens,null,2)+'\n');
function lum(hex){const x=hex.slice(1).match(/../g).map(h=>parseInt(h,16)/255).map(c=>c<=.04045?c/12.92:((c+.055)/1.055)**2.4);return x[0]*.2126+x[1]*.7152+x[2]*.0722;}
const pairs=[...['text','muted','negative','warning','info','positive','buy','sell'].flatMap(fg=>['background','surface','nested'].map(bg=>[fg,bg])),['faint','background'],['faint','surface'],...['action','negative','warning','info','positive','buy','sell'].map(bg=>['onAction',bg])];
const report=pairs.map(([fg,bg])=>{const a=lum(srgb[fg]),b=lum(srgb[bg]),ratio=(Math.max(a,b)+.05)/(Math.min(a,b)+.05);return {fg,bg,ratio:Number(ratio.toFixed(2)),aa:ratio>=4.5};});
const faintNestedRatio=(lum(srgb.faint)+.05)/(lum(srgb.nested)+.05);
writeFileSync('evidence/contrast.json',JSON.stringify({version:tokens.version,space:'sRGB fallback',pairs:report,unsupportedPairings:[{fg:'faint',bg:'nested',ratio:Number(faintNestedRatio.toFixed(2)),aa:false,alternative:'muted on nested (approved normal-text pair)'}],p3:'Not device-certified; use tested fallback if uncertain'},null,2)+'\n');
