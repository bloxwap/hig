import assert from 'node:assert/strict';
import React from 'react';
import {renderToString} from 'react-dom/server';
import {AnimatedNumberReadout} from '@bloxwap/hig/react/animated-number';
import {Button} from '@bloxwap/hig/react/button';
import {GestureSheet} from '@bloxwap/hig/react/gesture-sheet';
import {HIGProvider} from '@bloxwap/hig/react/provider';
import {tokens} from '@bloxwap/hig/tokens';
const html=renderToString(React.createElement(HIGProvider,null,React.createElement(Button,{style:{color:tokens.colors.text.srgb}},'Review order')));
assert.match(html,/Review order/);
const options={minimumFractionDigits:2,maximumFractionDigits:2};
const animatedProps={value:1234.5,options,stale:true,label:'Balance',duration:240,prefix:'$',suffix:' USD',trend:1};
const renderAnimated=()=>renderToString(React.createElement(HIGProvider,{locale:'de-DE'},React.createElement(AnimatedNumberReadout,animatedProps)));
const animated=renderAnimated(),formatted=new Intl.NumberFormat('de-DE',options).format(animatedProps.value);
assert.equal(animated,renderAnimated());
assert.ok(animated.includes(formatted),'SSR must include the final localized semantic reading');
assert.equal((animated.match(/aria-label="Balance:/g)??[]).length,1,'SSR must expose exactly one semantic reading');
assert.doesNotMatch(animated,/aria-live=/);
const animatedText=animated.replace(/<!--[\s\S]*?-->/g,'').replace(/<[^>]*>/g,'');
for(const text of ['$',formatted,' USD','(stale)'])assert.ok(animatedText.includes(text),`SSR visible reading must include ${text}`);
const renderGesture=()=>renderToString(React.createElement(GestureSheet,{open:true,onOpenChange:()=>{},title:'Review details',enableDynamicSizing:true,maxDynamicContentSize:480,trigger:React.createElement('button',null,'Open details')},React.createElement('p',null,'Details')));
const gesture=renderGesture();
assert.equal(gesture,renderGesture());assert.match(gesture,/Open details/);assert.match(gesture,/aria-expanded="true"/);
console.log('SSR deterministic token, animated-number and gesture-sheet renders passed');
